# Pedir dos números enteros e imprimir su suma, resta, multiplicación y división.

print('INGRESE:')
num1 = int(input("El primer número: "))
num2 = int(input("El segundo número: "))

print("\nSUMA DE AMBOS NÚMEROS: ")
suma = num1 + num2
print(suma)
print("\nRESTA DE AMBOS NÚMEROS: ")
resta = num1 - num2
print(resta)
print("\nPRODUCTO DE AMBOS NÚMEROS: ")
producto = num1 * num2
print(producto)
print("\nCOCIENTE DE AMBOS NÚMEROS: ")
cociente = num1 / num2
print(cociente)